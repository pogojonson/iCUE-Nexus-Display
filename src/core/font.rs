/// 7-segment overrides: only the digits are re-drawn as LCD segments in the
/// same 5×7 cell as classic, so every other character falls back to classic
/// and keeps the metrics identical.
fn segment_font() -> &'static FontDef {
    static FONT: OnceLock<FontDef> = OnceLock::new();
    FONT.get_or_init(|| {
        let mut masks = build_glyph_masks(&FONT_DATA, GLYPH_W, GLYPH_H);
        for &(ch, rows) in &SEGMENT_DATA {
            let idx = ch as i64 - ASCII_START as i64;
            if idx >= 0 && (idx as usize) < masks.len() {
                masks[idx as usize] = glyph_mask(&rows, GLYPH_W, GLYPH_H);
            }
        }
        FontDef {
            w: GLYPH_W,
            h: GLYPH_H,
            adv: (GLYPH_W + 1) as i32,
            gap: 1,
            masks,
        }
    })
}

/// Tiny5 Mono: 6×9 cell, advance 6 (same as classic), 1-px trailing gap.
