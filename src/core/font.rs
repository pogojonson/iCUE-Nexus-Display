//! Embedded bitmap font engine for the Corsair iCUE Nexus (640×48 BGRA) —
//! a faithful Rust port of `electron/nexus/font.ts`.
//!
//! # Buffer convention
//!
//! Every render function writes into a caller-owned pixel buffer of
//! `buf_w * buf_h * 4` bytes, row-major, **4 bytes per pixel in BGRA byte
//! order**: `buffer[off] = b`, `buffer[off+1] = g`, `buffer[off+2] = r`,
//! `buffer[off+3] = 0` — exactly the byte writes the original TypeScript
//! made into the Node `Buffer` that is sent to the device. `buf_w`/`buf_h`
//! are always passed explicitly (the renderer uses 640×48); nothing here
//! relies on defaults. Rows/columns whose scale-block falls outside the
//! buffer are skipped exactly like the TS loops, so edge glyphs are clipped
//! and nothing is ever written out of bounds.
//!
//! # Black-is-transparent (the level-4 halo)
//!
//! The alpha byte is always written as `0`: on the wire, pure black
//! (RGB 0,0,0) with A=0 marks a pixel as *untouched/transparent* — black is
//! transparent. The `shadow` style therefore cannot draw its halo in pure
//! black (it would vanish against an untouched background); it uses
//! RGB(4,4,4) instead — "level 4", the darkest shade that still survives
//! black — offset by (+1,+1) behind the glyphs.
//!
//! # Typefaces and styles
//!
//! The classic 5×7 ASCII font (labels) is the default; the value field can
//! opt in to `segment` (7-segment digits), `retro8` (8×8) and `tiny5`
//! (6×9) plus four `-thin` variants whose masks are skeletonized to a
//! 1-device-px hairline at the layout scale. Styles (`bold`, `italic`,
//! `underline`, `shadow`, …) and stroke `weight` (−1…+3 in half-steps) are
//! applied by [`render_text_styled`] / [`measure_text_styled`].

