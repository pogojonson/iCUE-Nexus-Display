/// Core glyph renderer: any font, optional italic shear (TS `renderCharFont`).
/// `code` is a UTF-16 code unit (TS checks `charCodeAt`); non-ASCII is skipped.
fn render_char_font(
    buffer: &mut [u8],
    font: &FontDef,
    code: u32,
    x: i64,
    y: i64,
    r: u8,
    g: u8,
    b: u8,
    scale: i64,
    shear: i64,
    buf_w: usize,
    buf_h: usize,
) {
    if !is_valid_code(code) {
        return;
    }
    let Some(masks) = font.masks.get((code - ASCII_START) as usize) else {
        return;
    };
    if scale <= 0 {
        return; // zero/negative scale: the TS block loops never execute
    }
    let buf_w64 = buf_w as i64;
    let buf_h64 = buf_h as i64;

    for row in 0..font.h {
        let mask = masks.get(row).copied().unwrap_or(0);
        if mask == 0 {
            continue;
        }
        let row_shift = if shear > 0 && font.h > 1 {
            ((font.h - 1 - row) as i64 * shear) / (font.h as i64 - 1)
        } else {
            0
        };
        let py = y + row as i64 * scale;
        // Clip rows above or below the buffer (whole scale-block must fit).
        if py < 0 || py + scale > buf_h64 {
            continue;
        }

        for col in 0..font.w {
            let sh = font.w - 1 - col;
            if sh >= 64 || mask & (1u64 << sh) == 0 {
                continue;
            }

            let px = x + col as i64 * scale + row_shift;
            // Clip columns outside the buffer.
            if px < 0 || px + scale > buf_w64 {
                continue;
            }

            // Draw the scaled pixel block.
            for sy in 0..scale {
                let buf_y = py + sy;
                if buf_y < 0 || buf_y >= buf_h64 {
                    continue;
                }
                for sx in 0..scale {
                    let buf_x = px + sx;
                    if buf_x < 0 || buf_x >= buf_w64 {
                        continue;
                    }
                    let offset = (buf_y as usize * buf_w + buf_x as usize) * 4;
                    if offset + 4 > buffer.len() {
                        continue; // Node ignored out-of-bounds Buffer writes
                    }
                    buffer[offset] = b;
                    buffer[offset + 1] = g;
                    buffer[offset + 2] = r;
                    buffer[offset + 3] = 0;
                }
            }
        }
    }
}

/// Draw the whole string once (one "pass" of `renderTextStyled`): glyphs
/// laid out at `font.adv * draw_scale` per UTF-16 code unit.
fn draw_pass(
    buffer: &mut [u8],
    font: &FontDef,
    text: &str,
    px: i64,
    py: i64,
    r: u8,
    g: u8,
    b: u8,
    draw_scale: i64,
    shear: i64,
    buf_w: usize,
    buf_h: usize,
) {
    let mut cursor = px;
    for unit in text.encode_utf16() {
        let code = unit as u32;
        if is_valid_code(code) {
            render_char_font(
                buffer, font, code, cursor, py, r, g, b, draw_scale, shear, buf_w, buf_h,
            );
        }
        cursor = cursor.saturating_add(font.adv as i64 * draw_scale);
    }
}

/// Fractional / negative stroke weights (−1…+3 in half-steps, excluding
/// integers ≥ 0 which keep the direct dilation path) — TS `renderTextFractional`.
///
/// Pipeline: rasterize the text at K× into a scratch mask (reusing
/// `render_char_font`, B channel = ink) → separable Chebyshev dilate (w>0)
/// or erode (w<0) by round(|w|·K) subpixels → K×K box-downsample to
/// coverage → alpha-blend the text color into the output buffer. Subpixel
/// edges come out anti-aliased; strokes land exactly |w| device px
/// thinner/thicker. `x`/`y` arrive already rounded by the caller (the TS
/// function re-rounds, a no-op).
fn render_text_fractional(
    buffer: &mut [u8],
    font: &FontDef,
    text: &str,
    x: i64,
    y: i64,
    r: u8,
    g: u8,
    b: u8,
    scale: i64,
    weight: f32,
    shear: i64,
    buf_w: usize,
    buf_h: usize,
) {
    let k = SS_K;
    let len = utf16_len(text);
    if len == 0 {
        return;
    }

    let radius = js_round(weight.abs() as f64 * k as f64) as i64; // subpixel morphology radius
    let margin = (radius + k - 1) / k; // Math.ceil(radius / K) — device-px border

    let Some(mask_w) = (len as i64)
        .checked_mul(font.adv as i64)
        .and_then(|v| v.checked_mul(scale))
        .map(|v| v + shear + 1 + margin * 2)
    else {
        return;
    };
    let Some(mask_h) = (font.h as i64)
        .checked_mul(scale)
        .map(|v| v + 1 + margin * 2)
    else {
        return;
    };
    if mask_w <= 0 || mask_h <= 0 {
        return;
    }
    let (Some(sub_w), Some(sub_h)) = (mask_w.checked_mul(k), mask_h.checked_mul(k)) else {
        return;
    };
    // OOM guard: the mask maps 1:1 onto (a margin around) the text, so any
    // realistic render is orders of magnitude below this.
    match sub_w.checked_mul(sub_h) {
        Some(n) if n > 0 && n <= (1 << 24) => {}
        _ => return,
    }

    let sub_len = (sub_w * sub_h) as usize;
    let mut mask_buf = vec![0u8; sub_len * 4];
    let mut ink = vec![0u8; sub_len];

    let mut cursor = margin * k;
    let y_sub = margin * k;
    for unit in text.encode_utf16() {
        if is_valid_code(unit as u32) {
            render_char_font(
                &mut mask_buf,
                font,
                unit as u32,
                cursor,
                y_sub,
                255,
                255,
                255,
                scale * k,
                shear * k,
                sub_w as usize,
                sub_h as usize,
            );
        }
        cursor += font.adv as i64 * scale * k;
    }
    for i in 0..sub_len {
        ink[i] = u8::from(mask_buf[i * 4] != 0); // B channel = ink
    }

    if radius > 0 {
        let mut tmp = vec![0u8; sub_len];
        let dilate = weight > 0.0;
        // Horizontal pass.
        for yy in 0..sub_h {
            let row = (yy * sub_w) as usize;
            for xx in 0..sub_w {
                let x0 = std::cmp::max(0, xx - radius); // Math.max(0, xx - radius)
                let x1 = std::cmp::min(sub_w - 1, xx + radius);
                let v = if dilate {
                    let mut v = 0u8;
                    for kk in x0..=x1 {
                        if ink[row + kk as usize] != 0 {
                            v = 1;
                            break;
                        }
                    }
                    v
                } else {
                    let mut v = 1u8;
                    for kk in x0..=x1 {
                        if ink[row + kk as usize] == 0 {
                            v = 0;
                            break;
                        }
                    }
                    v
                };
                tmp[row + xx as usize] = v;
            }
        }
        // Vertical pass.
        for xx in 0..sub_w {
            for yy in 0..sub_h {
                let y0 = std::cmp::max(0, yy - radius); // Math.max(0, yy - radius)
                let y1 = std::cmp::min(sub_h - 1, yy + radius);
                let v = if dilate {
                    let mut v = 0u8;
                    for kk in y0..=y1 {
                        if tmp[(kk * sub_w + xx) as usize] != 0 {
                            v = 1;
                            break;
                        }
                    }
                    v
                } else {
                    let mut v = 1u8;
                    for kk in y0..=y1 {
                        if tmp[(kk * sub_w + xx) as usize] == 0 {
                            v = 0;
                            break;
                        }
                    }
                    v
                };
                ink[(yy * sub_w + xx) as usize] = v;
            }
        }
    }

    // Box-downsample K×K → coverage; blend text color over existing pixels.
    let ox = x - margin;
    let oy = y - margin;
    let inv = 1.0 / (k * k) as f64;
    for dy in 0..mask_h {
        let buf_y = oy + dy;
        if buf_y < 0 || buf_y >= buf_h as i64 {
            continue;
        }
        for dx in 0..mask_w {
            let buf_x = ox + dx;
            if buf_x < 0 || buf_x >= buf_w as i64 {
                continue;
            }
            let sx0 = (dx * k) as usize;
            let sy0 = (dy * k) as usize;
            let mut count = 0u32;
            for sy in 0..k as usize {
                let row = (sy0 + sy) * sub_w as usize + sx0;
                for sx in 0..k as usize {
                    count += u32::from(ink[row + sx]);
                }
            }
            if count == 0 {
                continue;
            }
            let a = count as f64 * inv;
            let ia = 1.0 - a;
            let off = (buf_y as usize * buf_w + buf_x as usize) * 4;
            if off + 4 > buffer.len() {
                continue;
            }
            buffer[off] = js_round(buffer[off] as f64 * ia + b as f64 * a) as u8;
            buffer[off + 1] = js_round(buffer[off + 1] as f64 * ia + g as f64 * a) as u8;
            buffer[off + 2] = js_round(buffer[off + 2] as f64 * ia + r as f64 * a) as u8;
            // alpha byte untouched (0 for normal tiles, 255 under the nyan fill)
        }
    }
}

// ─── Public API: classic 5×7 (labels) ─────────────────────────────────

/// Render a single printable-ASCII character (classic 5×7 font only) into a
/// BGRA pixel buffer. BGRA byte order with alpha byte set to 0 — exactly
/// like TS: `buffer[off]=b, [off+1]=g, [off+2]=r, [off+3]=0`.
#[allow(dead_code)] // classic-font parity API (render_text drives masks directly)
pub fn render_char(
    buffer: &mut [u8],
    ch: char,
    x: i32,
    y: i32,
    r: u8,
    g: u8,
    b: u8,
    scale: i32,
    buf_w: usize,
    buf_h: usize,
) {
    render_char_font(
        buffer,
        classic_font(),
        ch as u32,
        x as i64,
        y as i64,
        r,
        g,
        b,
        scale as i64,
        0,
        buf_w,
        buf_h,
    );
}

/// Render a string of classic-font glyphs; returns the x-coordinate after
/// the last glyph (cursor advances `(GLYPH_W+1)*scale` per UTF-16 unit,
/// like TS `renderText`).
pub fn render_text(
    buffer: &mut [u8],
    text: &str,
    x: i32,
    y: i32,
    r: u8,
    g: u8,
    b: u8,
    scale: i32,
    buf_w: usize,
    buf_h: usize,
) -> i32 {
    let mut cursor = x as i64;
    for unit in text.encode_utf16() {
        let code = unit as u32;
        if is_valid_code(code) {
            render_char_font(
                buffer,
                classic_font(),
                code,
                cursor,
                y as i64,
                r,
                g,
                b,
                scale as i64,
                0,
                buf_w,
                buf_h,
            );
        }
        cursor = cursor.saturating_add((GLYPH_W as i64 + 1) * scale as i64);
    }
    clamp_i32(cursor)
}

/// Classic-font measurement: `width = len*5*scale + (len-1)*scale`,
/// `height = 7*scale` (empty text measures 0 wide).
pub fn measure_text(text: &str, scale: i32) -> TextSize {
    let len = utf16_len(text);
    let s = scale as f32;
    let width = if len == 0 {
        0.0
    } else {
        len as f32 * GLYPH_W as f32 * s + (len - 1) as f32 * s
    };
    TextSize {
        width,
        height: GLYPH_H as f32 * s,
    }
}

// ─── Public API: styled rendering (all typefaces / styles / weights) ──

/// Style-aware text renderer for the value field (TS `renderTextStyled`).
///
/// Styles (draw order): shadow pass (dark +1,+1 offset) → dilated glyph
/// passes (stroke weight: 2D, 0–3 extra px, default +1 for bold styles) →
/// underline bar. Regular with font `classic` is pixel-identical to
/// [`render_text`]. Fractional/negative weights render through the
/// supersampled mask path (anti-aliased sub-pixel edges).
///
/// `x`/`y` are rounded internally like TS (`x = Math.round(x)`).
/// Returns `x + measured width` (rounded x + width, as TS does).
pub fn render_text_styled(
    buffer: &mut [u8],
    text: &str,
    x: f32,
    y: f32,
    r: u8,
    g: u8,
    b: u8,
    scale: i32,
    opts: &TextStyleOptions,
    buf_w: usize,
    buf_h: usize,
) -> f32 {
    let thin = is_thin_font(opts.font);
    // Thin fonts draw their skeletonized masks 1:1 (the layout scale is
    // baked into the masks). Line Strength applies as extra px on the 1-px
    // hairline; Auto stays the hairline (bold never thickens a thin font).
    let thin_font = if thin {
        Some(thin_font_for(opts.font, scale))
    } else {
        None };
    let font: &FontDef = thin_font.as_deref().unwrap_or_else(|| font_for(opts.font));
    let draw_scale: i64 = if thin { 1 } else { scale as i64 };
    let flags = style_flags(opts.style);
    let shear = shear_for(opts.style, scale);

    // Fractional weights make `dim` fractional, so placement can arrive
    // fractional — snap once (JS Math.round) so every pixel loop below
    // addresses integer buffer indices. No-op for integers.
    let x = js_round(x as f64) as f32;
    let y = js_round(y as f64) as f32;
    let finite = x.is_finite() && y.is_finite();
    let xi = x as i64;
    let yi = y as i64;

    if !finite {
        // TS writes to `buffer[NaN]`, i.e. nothing visible — draw nothing.
        return x + measure_text_styled(text, scale, opts).width;
    }

    if flags.shadow {
        // Level 4 = darkest that survives black (see module docs).
        draw_pass(
            buffer, font, text, xi + 1, yi + 1, 4, 4, 4, draw_scale, shear, buf_w, buf_h,
        );
    }
    let weight = if thin {
        thin_weight_for(opts)
    } else {
        weight_for(opts, scale)
    };
    if weight < 0.0 || weight.fract() != 0.0 {
        // Sub-pixel path: dilate/erode in supersampled space, AA-blend back.
        // Pass `draw_scale` (not `scale`) so the thin fonts' baked-in k is
        // not applied a second time.
        render_text_fractional(
            buffer, font, text, xi, yi, r, g, b, draw_scale, weight, shear, buf_w, buf_h,
        );
    } else {
        // Stroke thickening: dilate every glyph pixel into a (1+w)×(1+w)
        // block so vertical stems AND horizontal bars gain the same px.
        let w_int = weight as i64;
        for dy in 0..=w_int {
            for dx in 0..=w_int {
                draw_pass(
                    buffer, font, text, xi + dx, yi + dy, r, g, b, draw_scale, shear, buf_w,
                    buf_h,
                );
            }
        }
    }

    if flags.underline && utf16_len(text) > 0 {
        let dim = measure_text_styled(text, scale, opts);
        let ul_h = underline_h_for(scale);
        let ul_y = js_round(y as f64 + font.h as f64 * draw_scale as f64 + weight as f64) as i64;
        // `dx < dim.width` with integer dx ⇒ ceil(width) iterations.
        let ul_w = if dim.width.is_finite() {
            dim.width.ceil() as i64
        } else {
            0
        };
        for dy in 0..ul_h {
            let buf_y = ul_y + dy;
            if buf_y < 0 || buf_y >= buf_h as i64 {
                continue;
            }
            for dx in 0..ul_w {
                let buf_x = xi + dx;
                if buf_x < 0 || buf_x >= buf_w as i64 {
                    continue;
                }
                let offset = (buf_y as usize * buf_w + buf_x as usize) * 4;
                if offset + 4 > buffer.len() {
                    continue;
                }
                buffer[offset] = b;
                buffer[offset + 1] = g;
                buffer[offset + 2] = r;
                buffer[offset + 3] = 0;
            }
        }
    }

    x + measure_text_styled(text, scale, opts).width
}

/// Measure a styled string without rendering (TS `measureTextStyled`) —
/// includes the width/height added by stroke weight (fractional values
/// included), italic (shear), shadow (+1) and underline (+bar). Thin ids
/// resolve to their base font's metrics; classic + regular matches
/// [`measure_text`] exactly.
pub fn measure_text_styled(text: &str, scale: i32, opts: &TextStyleOptions) -> TextSize {
    let font = font_for(opts.font); // thin ids resolve to their base's metrics
    let flags = style_flags(opts.style);
    // Same effective Line Strength as render_text_styled, so placement,
    // auto-shrink and the underline track the dilated ink exactly.
    let weight = if is_thin_font(opts.font) {
        thin_weight_for(opts)
    } else {
        weight_for(opts, scale)
    };
    let len = utf16_len(text);

    let mut width = if len == 0 {
        0.0
    } else {
        (len as f32 * font.adv as f32 - font.gap as f32) * scale as f32
    };
    if flags.italic {
        width += shear_for(opts.style, scale) as f32;
    }
    width += weight;
    if flags.shadow {
        width += 1.0;
    }
    if len > 0 && width < 1.0 {
        width = 1.0; // erosion can never collapse extent
    }

    let mut height = font.h as f32 * scale as f32 + weight;
    if flags.underline {
        height += underline_h_for(scale) as f32;
    }
    if flags.shadow {
        height += 1.0;
    }

    TextSize { width, height }
}

